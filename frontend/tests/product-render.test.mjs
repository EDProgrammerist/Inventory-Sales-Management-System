import assert from 'node:assert/strict'
import { test } from 'node:test'
import { createServer } from 'vite'

test('workspace routes and reference forms render with providers and accessible controls', { timeout: 60000 }, async () => {
  const server = await createServer({ server: { middlewareMode: true, hmr: false }, appType: 'custom', logLevel: 'error' })
  try {
    const { renderInventoryRoute, renderProductForm, renderReportChart, renderSupplierForm, renderOrderForm } = await server.ssrLoadModule('/scripts/product-render-check.tsx')
    const list = renderInventoryRoute('/inventory')
    assert.ok(list.includes('href="/inventory/maggi"'))
    const detail = renderInventoryRoute('/inventory/maggi')
    assert.ok(detail.includes('<title>Maggi · Kanban</title>'))
    for (const text of ['456567', 'Instant food', '13/4/23', 'Ronald Martin', '98789 86757', 'Sulur Branch', 'Singanallur Branch', '/inventory/maggi.png']) assert.ok(detail.includes(text), `Missing detail content: ${text}`)
    assert.equal((detail.match(/role="tab"/g) ?? []).length, 4)
    assert.equal((detail.match(/role="tabpanel"/g) ?? []).length, 4)
    assert.equal((detail.match(/aria-selected="true"/g) ?? []).length, 1)
    assert.ok(renderInventoryRoute('/inventory/missing-product').includes('Product not found'))
    const form = renderProductForm()
    for (const field of ['name', 'sku', 'category', 'price', 'quantity', 'unit', 'expiry', 'threshold']) assert.ok(form.includes(`id="product-${field}"`), `Missing form field: ${field}`)
    assert.ok(form.includes('Browse image'))
    assert.ok(form.includes('Discard'))
    const reports = renderInventoryRoute('/reports')
    for (const text of ['Best selling category', 'Profit &amp; Revenue', 'Best selling product', 'Tomato', '56841', 'Download profit and revenue CSV']) assert.ok(reports.includes(text), `Missing Reports content: ${text}`)
    const reportsLink = reports.match(/<a\b[^>]*href="\/reports"[^>]*>/)?.[0]
    assert.ok(reportsLink?.includes('aria-current="page"'))
    assert.ok(reports.includes('$58,000'))
    assert.ok(renderReportChart('quarterly').includes('Q3 (Sep)'))
    assert.ok(!renderReportChart('quarterly').includes('NaN'))
    const suppliers = renderInventoryRoute('/suppliers').replace(/<!--.*?-->/g, '')
    for (const value of ['Add Supplier', 'Richard Martin', 'Kit Kat', 'Not specified', 'Not Taking Return', 'Page 1 of 1']) assert.ok(suppliers.includes(value), `Missing Suppliers content: ${value}`)
    assert.equal((suppliers.match(/<tbody>([\s\S]*?)<\/tbody>/)?.[1].match(/<tr\b/g) ?? []).length, 14)
    assert.ok(suppliers.match(/<a\b[^>]*href="\/suppliers"[^>]*>/)?.[0].includes('aria-current="page"'))
    const supplierForm = renderSupplierForm()
    for (const field of ['name', 'product', 'category', 'price', 'phone', 'email']) assert.ok(supplierForm.includes(`id="supplier-${field}"`), `Missing supplier field: ${field}`)
    assert.equal((supplierForm.match(/type="radio"/g) ?? []).length, 2)
    assert.ok(supplierForm.includes('name="supplier-image"'))
    assert.ok(supplierForm.includes('Discard'))
    const orders = renderInventoryRoute('/orders').replace(/<!--.*?-->/g, '')
    for (const value of ['Overall Orders', 'Total Received', '$25000', 'Add Order', 'Order History', '7535', '11/12/22', 'Out for delivery', 'Page 1 of 1']) assert.ok(orders.includes(value), `Missing Orders content: ${value}`)
    assert.equal((orders.match(/<tbody>([\s\S]*?)<\/tbody>/)?.[1].match(/<tr\b/g) ?? []).length, 9)
    assert.ok(orders.match(/<a\b[^>]*href="\/orders"[^>]*>/)?.[0].includes('aria-current="page"'))
    const orderForm = renderOrderForm()
    for (const field of ['product','productId','category','value','quantity','unit','buyingPrice','expected']) assert.ok(orderForm.includes(`id="order-${field}"`), `Missing new order field: ${field}`)
    assert.ok(orderForm.includes('name="notifyOnDelivery"'))
    assert.ok(orderForm.match(/<input[^>]*type="checkbox"[^>]*checked/))
    assert.ok(orderForm.includes('no notification is scheduled'))
    assert.ok(orderForm.includes('Add Order'))
    assert.ok(!orderForm.includes('name="id"'))
    const stores = renderInventoryRoute('/manage-store')
    for (const value of ['Add Store', 'Singanallur Branch', 'Slur Branch', 'Gaandipuram Branch', 'Lisy Store', '044- 653763']) assert.ok(stores.includes(value), `Missing store content: ${value}`)
    assert.equal((stores.match(/<article\b/g) ?? []).length, 3)
    assert.equal((stores.match(/aria-label="Edit /g) ?? []).length, 3)
    assert.ok(stores.match(/<a\b[^>]*href="\/manage-store"[^>]*>/)?.[0].includes('aria-current="page"'))
  } finally {
    await server.close()
  }
})
